function formOf(n: number): keyof PluralForms {
  const abs = Math.abs(Math.trunc(n));
  if (abs === 0) return "zero";
  if (abs === 1) return "one";
  if (abs === 2) return "two";
  const mod = abs % 100;
  if (mod >= 3 && mod <= 10) return "few";
  if (mod >= 11 && mod <= 99) return "many";
  return "other";
}

export function formatCount(locale: Locale, n: number): string {
  return new Intl.NumberFormat("en-US").format(n);
}

export function plural(locale: Locale, n: number, forms: Record<Locale, PluralForms>): string {
  const key = locale === "ar" ? formOf(n) : n === 1 ? "one" : "other";
  return forms[locale][key].replace("{n}", formatCount(locale, n));
}

