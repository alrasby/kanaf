package com.kanaf.alrasby

import androidx.test.ext.junit.runners.AndroidJUnit4
import com.kanaf.alrasby.engine.SignedFeedPackage
import com.kanaf.alrasby.engine.SignedSignatureUpdate
import com.kanaf.alrasby.engine.VerifiedSignatureBundle
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.security.KeyPairGenerator
import java.security.MessageDigest
import java.security.Signature
import java.util.Base64
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Real Android parser/crypto verification for the same ZIP layout generated by
 * tools/signed_feed.py. Key is ephemeral, and rows are harmless test fixtures.
 */
@RunWith(AndroidJUnit4::class)
class SignedFeedPackageAndroidTest {
    private fun packageBytes(version: Long, data: ByteArray, key: java.security.PrivateKey,
                             changedData: ByteArray? = null): ByteArray {
        val sha = MessageDigest.getInstance("SHA-256").digest(data)
            .joinToString("") { "%02x".format(it.toInt() and 0xff) }
        val payload = "Kanaf-DB-v1\n$version\n$sha\n".toByteArray(Charsets.US_ASCII)
        val signer = Signature.getInstance("SHA256withRSA").apply {
            initSign(key)
            update(payload)
        }
        val manifest = "$version\n$sha\n" +
            Base64.getEncoder().encodeToString(signer.sign()) + "\n"
        return ByteArrayOutputStream().also { buffer ->
            ZipOutputStream(buffer).use { zip ->
                zip.putNextEntry(ZipEntry("signatures.tsv"))
                zip.write(changedData ?: data)
                zip.closeEntry()
                zip.putNextEntry(ZipEntry("manifest.txt"))
                zip.write(manifest.toByteArray(Charsets.US_ASCII))
                zip.closeEntry()
            }
        }.toByteArray()
    }

    @Test fun AndroidAcceptsCorrectPublisherSignatureAndRejectsTamperedDatabase() {
        val pair = KeyPairGenerator.getInstance("RSA").apply {
            initialize(2048)
        }.generateKeyPair()
        val data = ("d".repeat(64) + "\tEicar-Test-Signature\n")
            .toByteArray(Charsets.US_ASCII)
        val valid = SignedFeedPackage.parse(
            ByteArrayInputStream(packageBytes(7L, data, pair.private)))
        assertArrayEquals(data, valid.bytes)
        assertTrue(SignedSignatureUpdate.verify(valid.manifest, pair.public.encoded))
        val stored = ByteArrayOutputStream()
        VerifiedSignatureBundle.write(
            stored, valid.manifest.version, valid.manifest.sha256, valid.bytes
        )
        assertEquals(7L, VerifiedSignatureBundle.read(
            ByteArrayInputStream(stored.toByteArray())).version)

        val tampered = SignedFeedPackage.parse(ByteArrayInputStream(
            packageBytes(7L, data, pair.private,
                ("e".repeat(64) + "\tOther-Label\n").toByteArray(Charsets.US_ASCII))
        ))
        // Signature verification proves the manifest is authentic, but the
        // installed bundle must ALSO match its SHA. Never skip this check.
        assertTrue(SignedSignatureUpdate.verify(tampered.manifest, pair.public.encoded))
        assertThrows(Exception::class.java) {
            VerifiedSignatureBundle.write(
                ByteArrayOutputStream(), tampered.manifest.version,
                tampered.manifest.sha256, tampered.bytes)
        }
    }
}
